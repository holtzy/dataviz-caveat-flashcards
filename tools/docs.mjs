// Writes the files generated from caveats.json, the single source for the cards' text:
//   - the card list in README.md (between the cards:start / cards:end markers)
//   - caveats.md, the same caveats as a checklist an AI (or a person) can review a chart against
// Usage: node tools/docs.mjs   (no dependencies)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RAW = "https://raw.githubusercontent.com/holtzy/dataviz-caveat-flashcards/main";
const { sections, caveats } = JSON.parse(fs.readFileSync(path.join(REPO, "caveats.json"), "utf8"));

// Every caveat must belong to a listed section and have its images.
for (const c of caveats) {
  if (!sections.includes(c.section)) throw new Error(`${c.id}: unknown section "${c.section}"`);
  if (!fs.existsSync(path.join(REPO, `png/${c.id}-horiz.png`))) throw new Error(`${c.id}: png/${c.id}-horiz.png is missing`);
}
const bySection = sections.map((title) => ({ title, cards: caveats.filter((c) => c.section === title) }));

// README.md
const list = bySection
  .map((s) => [`## ${s.title}`, ...s.cards.map((c) => `- ${c.title} · [link](png/${c.id}-horiz.png)`)].join("\n"))
  .join("\n\n");
const readmePath = path.join(REPO, "README.md");
const readme = fs.readFileSync(readmePath, "utf8");
const START = "<!-- cards:start -->", END = "<!-- cards:end -->";
if (!readme.includes(START) || !readme.includes(END)) throw new Error("README.md: cards:start / cards:end markers not found");
fs.writeFileSync(
  readmePath,
  readme.slice(0, readme.indexOf(START) + START.length) + `\n${list}\n` + readme.slice(readme.indexOf(END)),
);

// caveats.md
const flat = (s) => s.replace(/\n/g, " ");
const md = [
  "# Dataviz caveats checklist",
  "",
  "<!-- Generated by tools/docs.mjs from caveats.json. Edit caveats.json, not this file. -->",
  "",
  `The most common data visualization caveats, from the [Data to Viz flashcards](https://github.com/holtzy/dataviz-caveat-flashcards). ${caveats.length} caveats in ${sections.length} sections.`,
  "",
  "To review a chart, go through every caveat. Flag it only when the chart shows what **Look for** describes",
  "and the **Fine when** exception does not apply. For each flagged caveat, say what you saw and how to fix it.",
  "",
  ...bySection.flatMap((s) => [
    `## ${s.title}`,
    "",
    ...s.cards.flatMap((c) => [
      `### ${c.title}`,
      "",
      `- **Look for:** ${c.look_for}`,
      `- **Why it matters:** ${c.why}`,
      `- **Fix:** ${c.fix}`,
      ...(c.ok_when ? [`- **Fine when:** ${c.ok_when}`] : []),
      `- **Card:** ${flat(c.caption)} ([image](${RAW}/png/${c.id}-horiz.png))`,
      ...(c.article ? [`- **Read more:** ${c.article}`] : []),
      "",
    ]),
  ]),
].join("\n");
fs.writeFileSync(path.join(REPO, "caveats.md"), md);

console.log(`${caveats.length} caveats in ${sections.length} sections: README.md and caveats.md written`);
